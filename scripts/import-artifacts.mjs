import { createHash, createPublicKey, randomUUID, verify } from "node:crypto";
import { existsSync, readFileSync, renameSync, unlinkSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifactPaths = Object.freeze(["src/generated/abis.ts", "src/generated/deployments.ts"]);
const provenancePath = "provenance/current.json";
const authorityConfig = JSON.parse(readFileSync(resolve(root, "config/artifact-authorities.json"), "utf8"));

function fail(message) {
  throw new Error(`contract artifact import: ${message}`);
}

function exactObject(value, fields, path) {
  if (!value || Array.isArray(value) || typeof value !== "object") fail(`${path} must be an object`);
  const actual = Object.keys(value).sort();
  const expected = [...fields].sort();
  const unexpected = actual.filter((field) => !expected.includes(field));
  const missing = expected.filter((field) => !actual.includes(field));
  if (missing.length > 0) fail(`${path} is missing ${missing.join(", ")}`);
  if (unexpected.length > 0) fail(`${path} contains unexpected fields: ${unexpected.join(", ")}`);
  return value;
}

export function canonicalJsonBytes(value) {
  const normalize = (item) => {
    if (Array.isArray(item)) return item.map(normalize);
    if (item && typeof item === "object") {
      return Object.fromEntries(Object.keys(item).sort().map((key) => [key, normalize(item[key])]));
    }
    return item;
  };
  return Buffer.from(JSON.stringify(normalize(value)));
}

function parseJsonAt(source, start, label) {
  const opening = source[start];
  if (!["{", "[", '"'].includes(opening)) fail(`${label} is not a JSON value`);
  if (opening === '"') {
    let escaped = false;
    for (let index = start + 1; index < source.length; index += 1) {
      if (!escaped && source[index] === '"') return { value: JSON.parse(source.slice(start, index + 1)), end: index + 1 };
      escaped = !escaped && source[index] === "\\";
      if (source[index] !== "\\") escaped = false;
    }
  } else {
    const stack = [];
    let string = false;
    let escaped = false;
    for (let index = start; index < source.length; index += 1) {
      const character = source[index];
      if (string) {
        if (!escaped && character === '"') string = false;
        escaped = !escaped && character === "\\";
        if (character !== "\\") escaped = false;
        continue;
      }
      if (character === '"') string = true;
      else if (character === "{" || character === "[") stack.push(character);
      else if (character === "}" || character === "]") {
        const expected = character === "}" ? "{" : "[";
        if (stack.pop() !== expected) fail(`${label} has unbalanced JSON`);
        if (stack.length === 0) return { value: JSON.parse(source.slice(start, index + 1)), end: index + 1 };
      }
    }
  }
  fail(`${label} contains incomplete JSON`);
}

function parseGeneratedModule(bytes, header, allowedNames) {
  const source = bytes.toString("utf8");
  if (!source.startsWith(header)) fail("generated module header is invalid");
  let offset = header.length;
  const exports = new Map();
  while (offset < source.length) {
    if (source.slice(offset) === "\n") {
      offset += 1;
      break;
    }
    const prefix = offset === header.length
      ? "export const "
      : (source.startsWith("\n\nexport const ", offset) ? "\n\nexport const " : "\nexport const ");
    if (!source.startsWith(prefix, offset)) fail("generated module contains non-canonical TypeScript");
    offset += prefix.length;
    const nameMatch = /^[A-Za-z_$][0-9A-Za-z_$]*/.exec(source.slice(offset));
    if (!nameMatch) fail("generated module export name is invalid");
    const name = nameMatch[0];
    if (!allowedNames.has(name) || exports.has(name)) fail(`generated module has unexpected or duplicate export ${name}`);
    offset += name.length;
    if (!source.startsWith(" = ", offset)) fail(`generated module export ${name} is malformed`);
    offset += 3;
    const parsed = parseJsonAt(source, offset, name);
    offset = parsed.end;
    if (!source.startsWith(" as const;", offset)) fail(`generated module export ${name} is not canonical`);
    offset += " as const;".length;
    exports.set(name, parsed.value);
  }
  if (exports.size !== allowedNames.size) fail("generated module export set is incomplete");
  return exports;
}

function validateGeneratedSemantics(files, value) {
  const abiHeader = "// Generated by scripts/generate-launchpad-sdk.mjs; do not edit.\n";
  const abiNames = new Set([
    "launchpadAbi", "routerAbi", "feeControllerAbi", "graduationPoolAbi", "launchTokenAbi",
    "launchEscrowAbi", "launchEscrowDeployerAbi", "proxyAdminIdentityAbi",
    "proxyUpgradeGateIdentityAbi", "lbFactoryIdentityAbi", "lbRouterIdentityAbi",
    "abiSignatures", "ABI_REVISION",
  ]);
  const abis = parseGeneratedModule(files.get("src/generated/abis.ts"), abiHeader, abiNames);
  if (abis.get("ABI_REVISION") !== value.abiRevision) fail("ABI module does not declare the handoff revision");

  const deploymentHeader = "// Generated by scripts/generate-launchpad-sdk.mjs from config/blockchains.json; do not edit.\n";
  const deployments = parseGeneratedModule(
    files.get("src/generated/deployments.ts"), deploymentHeader, new Set(["deploymentManifest"]),
  ).get("deploymentManifest");
  const network = Object.values(deployments?.robinhood ?? {}).find((candidate) => candidate?.chain_id === value.chainId);
  if (!network || network.chain_data?.deployment_id !== value.deploymentId
    || network.chain_data?.start_block !== value.startBlock
    || network.contracts?.start_block !== value.startBlock
    || network.contracts?.release_id !== value.releaseId
    || network.contracts?.abi_revision !== value.abiRevision) {
    fail("deployment module does not match the handoff identity");
  }
}

function verifyAuthoritySignature(value, trustedAuthorities) {
  const authority = trustedAuthorities.find((candidate) => candidate?.id === value.producerId);
  if (!authority) fail("producer identity is not trusted by config/artifact-authorities.json");
  exactObject(value.signature, ["algorithm", "keyId", "valueBase64"], "signature");
  if (value.signature.algorithm !== "Ed25519") fail("signature algorithm is unsupported");
  const key = authority.keys?.find((candidate) => candidate?.id === value.signature.keyId && candidate?.algorithm === "Ed25519");
  if (!key || typeof key.publicKeyPem !== "string") fail("signature key is not trusted for this producer");
  const signature = Buffer.from(value.signature.valueBase64, "base64");
  if (signature.length !== 64 || signature.toString("base64") !== value.signature.valueBase64) fail("signature is malformed");
  const { signature: _signature, ...payload } = value;
  if (!verify(null, canonicalJsonBytes(payload), createPublicKey(key.publicKeyPem), signature)) {
    fail("signature verification failed");
  }
}

export function decodeArtifactHandoff(value, { trustedAuthorities = authorityConfig.authorities } = {}) {
  exactObject(value, [
    "schemaVersion", "producerId", "releaseId", "chainId", "deploymentId", "startBlock",
    "abiRevision", "artifacts", "signature",
  ], "handoff");
  if (value.schemaVersion !== 2) fail("schemaVersion must be 2");
  if (!Array.isArray(trustedAuthorities)) fail("trusted authority config is invalid");
  if (!Number.isSafeInteger(value.chainId) || value.chainId <= 0) fail("chainId must be positive");
  if (!Number.isSafeInteger(value.startBlock) || value.startBlock < 0) fail("startBlock is invalid");
  if (!/^[0-9A-Za-z][0-9A-Za-z._-]*$/.test(value.releaseId)) fail("releaseId is invalid");
  const deploymentPattern = new RegExp(`^${value.chainId}:launchpad:0x[0-9a-f]{40}:${value.startBlock}$`);
  if (!deploymentPattern.test(value.deploymentId)) fail("deploymentId does not match chainId and startBlock");
  if (!/^sha256:[0-9a-f]{64}$/.test(value.abiRevision)) fail("abiRevision is invalid");
  if (!Array.isArray(value.artifacts) || value.artifacts.length !== artifactPaths.length) {
    fail("handoff must contain the complete generated artifact set");
  }
  verifyAuthoritySignature(value, trustedAuthorities);

  const files = new Map();
  for (const artifact of value.artifacts) {
    exactObject(artifact, ["path", "sha256", "contentBase64"], "artifact");
    if (!artifactPaths.includes(artifact.path) || files.has(artifact.path)) fail(`unexpected or duplicate path ${artifact.path}`);
    if (!/^[0-9a-f]{64}$/.test(artifact.sha256)) fail(`${artifact.path} sha256 is invalid`);
    const bytes = Buffer.from(artifact.contentBase64, "base64");
    if (bytes.length === 0 || bytes.toString("base64") !== artifact.contentBase64) fail(`${artifact.path} is not canonical base64`);
    const actual = createHash("sha256").update(bytes).digest("hex");
    if (actual !== artifact.sha256) fail(`${artifact.path} hash mismatch`);
    files.set(artifact.path, bytes);
  }
  for (const path of artifactPaths) if (!files.has(path)) fail(`missing ${path}`);
  validateGeneratedSemantics(files, value);

  const provenance = {
    ...value,
    artifacts: value.artifacts.map(({ contentBase64: _contentBase64, ...artifact }) => artifact),
  };
  return Object.freeze({ files, provenance });
}

export function writeArtifactImport({ files, provenance }, { rootDir = root, rename = renameSync } = {}) {
  const entries = [
    ...artifactPaths.map((path) => [path, files.get(path)]),
    [provenancePath, Buffer.from(`${JSON.stringify(provenance, null, 2)}\n`)],
  ];
  const originals = new Map(entries.map(([path]) => {
    const target = resolve(rootDir, path);
    return [path, existsSync(target) ? readFileSync(target) : undefined];
  }));
  const staged = new Map();
  try {
    for (const [path, contents] of entries) {
      const temporary = `${resolve(rootDir, path)}.import-${randomUUID()}`;
      writeFileSync(temporary, contents, { flag: "wx" });
      staged.set(path, temporary);
    }
    for (const [path] of entries) rename(staged.get(path), resolve(rootDir, path));
  } catch (error) {
    for (const [path, contents] of originals) {
      const target = resolve(rootDir, path);
      if (contents === undefined) {
        if (existsSync(target)) unlinkSync(target);
      } else {
        writeFileSync(target, contents);
      }
    }
    throw error;
  } finally {
    for (const temporary of staged.values()) if (existsSync(temporary)) unlinkSync(temporary);
  }
}

function parseArgs(argv) {
  if (argv.length !== 2 || argv[0] !== "--manifest" || !argv[1]) {
    fail("usage: npm run artifacts:import -- --manifest <handoff.json>");
  }
  return resolve(argv[1]);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const manifestPath = parseArgs(process.argv.slice(2));
    const handoff = JSON.parse(readFileSync(manifestPath, "utf8"));
    const decoded = decodeArtifactHandoff(handoff);
    writeArtifactImport(decoded);
    console.log(`imported ${decoded.files.size} artifacts for ${decoded.provenance.producerId}/${decoded.provenance.releaseId}`);
  } catch (error) {
    console.error(error instanceof Error ? error.message : error);
    process.exitCode = 1;
  }
}
